alter table public.events enable row level security;
alter table public.rsvps enable row level security;

-- Cualquier invitado puede registrar una respuesta en un evento activo.
drop policy if exists "public can insert rsvps" on public.rsvps;
create policy "public can insert rsvps"
on public.rsvps for insert
to anon, authenticated
with check (
  exists (
    select 1 from public.events
    where events.slug = event_slug and events.is_active = true
  )
);

-- Solo usuarios autenticados del proyecto pueden consultar y administrar RSVP.
drop policy if exists "authenticated can read rsvps" on public.rsvps;
create policy "authenticated can read rsvps"
on public.rsvps for select
to authenticated
using (true);

drop policy if exists "authenticated can update rsvps" on public.rsvps;
create policy "authenticated can update rsvps"
on public.rsvps for update
to authenticated
using (true)
with check (true);

drop policy if exists "authenticated can delete rsvps" on public.rsvps;
create policy "authenticated can delete rsvps"
on public.rsvps for delete
to authenticated
using (true);

-- Lectura pública mínima de eventos activos (útil para validaciones futuras).
drop policy if exists "public can read active events" on public.events;
create policy "public can read active events"
on public.events for select
to anon, authenticated
using (is_active = true);

