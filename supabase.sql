create table if not exists public.events (
  slug text primary key,
  title text not null,
  event_date timestamptz not null,
  location text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  event_slug text not null references public.events(slug)
    on update cascade
    on delete cascade,
  reference_code text not null unique,
  name text not null check (char_length(name) between 2 and 100),
  phone text not null check (char_length(phone) between 8 and 20),
  attendance text not null check (attendance in ('confirmado', 'no_asiste')),
  guests_count integer not null default 0 check (guests_count between 0 and 10),
  guest_names text not null default '' check (char_length(guest_names) <= 220),
  message text not null default '' check (char_length(message) <= 400),
  checked_in boolean not null default false,
  checked_in_at timestamptz,
  created_at timestamptz not null default now(),
  constraint valid_checkin_date check (
    (checked_in = false and checked_in_at is null)
    or
    (checked_in = true and checked_in_at is not null)
  )
);

-- Usuarios de Supabase Auth autorizados para administrar LN Studio.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default now()
);

create index if not exists rsvps_event_slug_idx
  on public.rsvps(event_slug);

create index if not exists rsvps_created_at_idx
  on public.rsvps(created_at desc);

-- Función segura usada por las políticas RLS.
create or replace function public.is_ln_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_ln_admin() from public;
grant execute on function public.is_ln_admin() to authenticated;

