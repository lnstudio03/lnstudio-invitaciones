create table if not exists public.events (
  slug text primary key,
  title text not null,
  event_date timestamptz not null,
  location text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  event_slug text not null references public.events(slug) on update cascade on delete cascade,
  reference_code text not null unique,
  name text not null check (char_length(name) between 2 and 100),
  phone text not null check (char_length(phone) between 8 and 20),
  attendance text not null check (attendance in ('confirmado','no_asiste')),
  guests_count integer not null default 0 check (guests_count between 0 and 10),
  guest_names text default '',
  message text default '',
  checked_in boolean not null default false,
  checked_in_at timestamptz,
  created_at timestamptz not null default now()
);


-- Compatibilidad si la tabla ya existía antes de esta versión.
alter table public.rsvps add column if not exists reference_code text;
update public.rsvps set reference_code = 'LEGACY-' || id where reference_code is null;
alter table public.rsvps alter column reference_code set not null;
create unique index if not exists rsvps_reference_code_idx on public.rsvps(reference_code);

create index if not exists rsvps_event_slug_idx on public.rsvps(event_slug);
create index if not exists rsvps_created_at_idx on public.rsvps(created_at desc);

