-- RLS: seguridad obligatoria para tablas públicas.
alter table public.events enable row level security;
alter table public.rsvps enable row level security;
alter table public.admin_users enable row level security;

-- Permisos del Data API.
grant select on public.events to anon, authenticated;
grant insert on public.rsvps to anon, authenticated;
grant select, update, delete on public.rsvps to authenticated;
grant usage, select on sequence public.rsvps_id_seq to anon, authenticated;

-- EVENTOS -----------------------------------------------------
drop policy if exists "public can read active events" on public.events;
create policy "public can read active events"
on public.events
for select
to anon, authenticated
using (is_active = true);

drop policy if exists "admins can read every event" on public.events;
create policy "admins can read every event"
on public.events
for select
to authenticated
using ((select public.is_ln_admin()));

-- RSVP PÚBLICO -------------------------------------------------
-- Un visitante solo puede crear una respuesta para un evento activo.
-- No puede marcarse como registrado en la entrada desde el formulario.
drop policy if exists "public can insert rsvps" on public.rsvps;
create policy "public can insert rsvps"
on public.rsvps
for insert
to anon, authenticated
with check (
  checked_in = false
  and checked_in_at is null
  and exists (
    select 1
    from public.events
    where events.slug = rsvps.event_slug
      and events.is_active = true
  )
);

-- PANEL ADMINISTRATIVO ----------------------------------------
drop policy if exists "admins can read rsvps" on public.rsvps;
create policy "admins can read rsvps"
on public.rsvps
for select
to authenticated
using ((select public.is_ln_admin()));

drop policy if exists "admins can update rsvps" on public.rsvps;
create policy "admins can update rsvps"
on public.rsvps
for update
to authenticated
using ((select public.is_ln_admin()))
with check ((select public.is_ln_admin()));

drop policy if exists "admins can delete rsvps" on public.rsvps;
create policy "admins can delete rsvps"
on public.rsvps
for delete
to authenticated
using ((select public.is_ln_admin()));

